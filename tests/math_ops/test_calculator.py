import pytest

from src.math_ops import calculator


@pytest.mark.parametrize(
    "first, second, op, expected",
    [
        (0, 0, "+", 0),
        (-2, -4, "+", -6),
        (23, 12, "+", 35),
        (-3, 2, "+", -1),
        (2.3, 1.2, "+", 3.5),
        (0, 0, "-", 0),
        (-2, -4, "-", 2),
        (23, 12, "-", 11),
        (-3, 2, "-", -5),
        (2.3, 1.2, "-", 1.0999999999999999),
        (0, 0, "*", 0),
        (-2, -4, "*", 8),
        (23, 2, "*", 46),
        (-3, 2, "*", -6),
        (2.3, 1.2, "*", 2.76),
        (0, 0, "/", None),
        (-2, -4, "/", 0),
        (23, 12, "/", 1.0),
        (-3, 2, "/", -2),
        (2.3, 1.2, "/", 1.0),
        (0, 0, "%", None),
        (-2, -4, "%", -2),
        (23, 12, "%", 11),
        (-3, 2, "%", 1),
        (2.3, 1.2, "%", 1.0999999999999999),
        (0, 0, "$", None),
        (0, 0, "!", None),
        (0, 0, "~", None),
        (0, 0, "|", None),
        (0, 0, "&", None),
    ],
)
def test_calculator[T: (int, float)](first: T, second: T, op: str, expected: T) -> None:
    assert calculator(first, second, op) == expected
